def test_frontend_generator_can_instantiate_with_project(tmp_path):
    from src.agents.frontend_generator import FrontendGenerator
    from src.core.workspace import Project

    project = Project(
        id="test", name="test", description="test",
        root_dir=str(tmp_path), tech_stack={"frontend": "nextjs"},
        target="web", profile_id=1,
    )
    gen = FrontendGenerator(project=project)
    assert gen is not None
    # Prefer generate_component if available
    if hasattr(gen, "generate_component"):
        from src.agents.frontend_generator import ComponentSpec
        spec = ComponentSpec(name="HelloCard", type="component", description="A hello card")
        result = gen.generate_component(spec)
        assert result is not None
        text = " ".join(str(v) for v in (result.values() if isinstance(result, dict) else [result]))
        assert len(text) > 10


