@pytest.mark.asyncio
async def test_pipeline_writes_artifacts_to_disk(tmp_path):
    """Full pipeline (mocked NIM) must write non-empty files under project_dir."""
    from backend.agent_pipeline import AgentPipeline

    mock = AsyncMock()

    async def fake_stream(messages, model=None, temperature=0.4, max_tokens=4096):
        system = (messages[0].get("content") or "") if messages else ""
        user = (messages[1].get("content") or "") if len(messages) > 1 else ""
        blob = (system + " " + user).lower()
        if "plan" in blob or "architect" in blob:
            yield "# Plan\n\nTech stack: Next.js + FastAPI + Postgres\n"
        elif "design" in blob:
            yield "# Design\n\nColors: primary #76B900\n"
        elif "frontend" in blob or "react" in blob:
            yield "export default function App() { return <div>Hello</div>; }\n"
        elif "backend" in blob or "fastapi" in blob:
            yield "from fastapi import FastAPI\napp = FastAPI()\n@app.get('/health')\ndef health(): return {'ok': True}\n"
        elif "docker" in blob or "integration" in blob:
            yield "version: '3.8'\nservices:\n  web:\n    image: node:20\n"
        else:
            yield "# artifact\ncontent generated by agent\n"

    mock.chat_stream = fake_stream
    mock.list_models = AsyncMock(return_value=[MagicMock(id="meta/llama-3.1-8b-instruct")])
    mock.health_check = AsyncMock(return_value={"ready": True, "live": True})
    mock.close = AsyncMock()

    pipeline = AgentPipeline(mock)
    ctx = await pipeline.run(
        user_prompt="Build a simple hello SaaS with health endpoint",
        project_dir=str(tmp_path),
    )

    assert ctx is not None
    files = [p for p in tmp_path.rglob("*") if p.is_file()]
    assert len(files) >= 1, f"Expected generated files, found {files}"
    for f in files:
        assert f.stat().st_size > 0, f"{f} is empty"


