ROOT_DIR = Path(__file__).resolve().parents[2]

class TestL1VisionAndNIMExclusivity:
    """Validate L1 Vision Requirements: Strict NIM usage without silent mock fallbacks."""

    def test_strict_nim_mode_raises_when_key_missing(self, monkeypatch):
        """Ensure system fails loudly instead of falling back to mock when NIM key is absent."""
        for key in ["NIM_API_KEY", "NVIDIA_API_KEY", "NGC_API_KEY"]:
            monkeypatch.delenv(key, raising=False)
        
        from backend.nim_client import NIMClient
        with pytest.raises(ValueError, match="NVIDIA NIM API key required"):
            NIMClient(api_key="")

    def test_no_mock_fallback_in_pipeline_router(self):
        """Audit backend/app/api/pipeline.py to verify default execution does not silently inject mocks."""
        pipeline_api_file = ROOT_DIR / "backend" / "app" / "api" / "pipeline.py"
        assert pipeline_api_file.exists()
        content = pipeline_api_file.read_text(encoding="utf-8")
        
        # Verify strict check exists before running mock client
        assert "use_mock: bool = False" in content

class TestNextjsBuildPipelineAndHydration:
    """Validate Next.js Build Pipeline configuration and Component Hydration Safety."""

    def test_next_config_has_standalone_output(self):
        """Validate Next.js configuration includes standalone output for Docker containerization."""
        next_config_path = ROOT_DIR / "frontend" / "next.config.js"
        assert next_config_path.exists(), "frontend/next.config.js must exist"
        
        content = next_config_path.read_text(encoding="utf-8")
        assert "output: 'standalone'" in content or 'output: "standalone"' in content, (
            "frontend/next.config.js must specify output: 'standalone' for production Docker builds"
        )

    def test_workspace_component_hydration_safety(self):
        """Audit workspace page to ensure dynamic date formatting is SSR/hydration safe."""
        workspace_page = ROOT_DIR / "frontend" / "src" / "app" / "workspace" / "page.tsx"
        assert workspace_page.exists()
        
        content = workspace_page.read_text(encoding="utf-8")
        
        # Checking for unsafe inline dynamic date formatting in JSX render
        unsafe_pattern = r'\{[a-zA-Z0-9_.]+\.toLocaleTimeString\(\)\}'
        matches = re.findall(unsafe_pattern, content)
        
        # If dynamic dates are rendered, mounted state guarding must be present
        if matches:
            assert "mounted" in content or "useEffect" in content, (
                "Direct call to toLocaleTimeString() in JSX causes hydration mismatch errors. "
                "Component must use mounted state guard."
            )

class TestDockerContainerArchitecture:
    """Validate Multi-stage Docker Container Configuration."""

    def test_frontend_dockerfile_multistage_structure(self):
        """Verify frontend Dockerfile utilizes multi-stage build with standalone runner."""
        dockerfile_path = ROOT_DIR / "frontend" / "Dockerfile"
        if not dockerfile_path.exists():
            pytest.fail("frontend/Dockerfile does not exist for production Next.js build")

        content = dockerfile_path.read_text(encoding="utf-8")
        assert "FROM node" in content
        assert "AS runner" in content or "AS builder" in content, "Dockerfile should use multi-stage builds"
        assert ".next/standalone" in content, "Dockerfile runner stage must copy .next/standalone artifacts"

    def test_docker_compose_config_validity(self):
        """Ensure docker-compose config passes basic structural requirements."""
        dc_path = ROOT_DIR / "docker-compose.yml"
        if not dc_path.exists():
            dc_path = ROOT_DIR / "docker-compose.smoke.yml"
        
        assert dc_path.exists(), "A docker-compose file must exist"
        content = dc_path.read_text(encoding="utf-8")
        assert "services:" in content
        assert "NIM_API_KEY" in content or "NVIDIA_API_KEY" in content

class TestAgentCodeGenerationQuality:
    """Validate AST correctness of code generated by agents."""

    def test_generated_backend_code_ast_validity(self):
        """Verify backend code generator outputs syntactically valid Python code."""
        from src.agents.backend_generator import BackendGenerator, RouteSpec
        from src.core.workspace import Project

        project = Project(
            id="test-proj", name="test-proj", description="test",
            root_dir=str(ROOT_DIR), tech_stack={"backend": "fastapi"},
            target="web", profile_id=1,
        )
        gen = BackendGenerator(project=project)
        spec = RouteSpec(path="/api/v1/test", method="GET", name="test_route", description="Test Endpoint")
        
        artifacts = gen.generate_route(spec)
        assert isinstance(artifacts, dict)
        
        for filepath, code in artifacts.items():
            if filepath.endswith(".py"):
                try:
                    import ast
                    ast.parse(code)
                except SyntaxError as e:
                    pytest.fail(f"Generated Python code in {filepath} has invalid syntax: {e}")